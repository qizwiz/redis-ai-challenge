@mcp.tool()
def monitor_buffer_state() -> str:
    """Monitor the state of this buffer agent's org file"""
    
    org_file = "{org_file}"
    agent_name = "{agent_name}"
    
    try:
        # Check if org file exists and get stats
        if os.path.exists(org_file):
            stat = os.stat(org_file)
            file_size = stat.st_size
            last_modified = stat.st_mtime
            
            # Read current content
            with open(org_file, 'r') as f:
                content = f.read()
                line_count = len(content.split('\\n'))
                char_count = len(content)
            
            # Update Redis with current state
            state = {{
                "file_exists": True,
                "size": file_size,
                "lines": line_count,
                "characters": char_count,
                "last_modified": last_modified,
                "last_check": time.time()
            }}
            
            r.hset(f"agent:{{agent_name}}:state", mapping=state)
            
            return f"""📄 BUFFER STATE: {{agent_name}}
File: {{org_file}}
Size: {{file_size}} bytes ({{line_count}} lines)
Characters: {{char_count}}
Last Modified: {{time.ctime(last_modified)}}
Status: ✅ Active and monitored
"""
        else:
            return f"❌ Org file not found: {{org_file}}"
            
    except Exception as e:
        return f"❌ Error monitoring buffer: {{e}}"

