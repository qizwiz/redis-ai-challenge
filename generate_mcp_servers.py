@mcp.tool()
def discover_relationships() -> str:
    """Discover relationships with other buffer agents"""
    
    agent_name = "{agent_name}"
    org_file = "{org_file}"
    
    try:
        # Read current content
        with open(org_file, 'r') as f:
            content = f.read()
        
        # Find potential relationships
        relationships = []
        
        # Look for links to other org files
        import re
        links = re.findall(r'\\[\\[([^\\]]+)\\]\\]', content)
        for link in links:
            if link.endswith('.org'):
                relationships.append({{
                    "type": "org_link",
                    "target": link,
                    "strength": "direct"
                }})
        
        # Look for agent mentions
        network_agents = list(r.smembers("active_buffer_agents"))
        for other_agent in network_agents:
            if other_agent != agent_name and other_agent.replace('_agent', '') in content:
                relationships.append({{
                    "type": "content_mention",
                    "target": other_agent,
                    "strength": "indirect"
                }})
        
        # Store relationships in Redis graph
        for rel in relationships:
            r.hset(f"relationship:{{agent_name}}:{{rel['target']}}", mapping=rel)
            r.sadd(f"agent:{{agent_name}}:relationships", rel['target'])
        
        return f"""🔗 RELATIONSHIP DISCOVERY: {{agent_name}}
Discovered {{len(relationships)}} relationships:

{{len(relationships)}} relationships found

✅ Relationships stored in knowledge graph
"""
        
    except Exception as e:
        return f"❌ Error discovering relationships: {{e}}"

