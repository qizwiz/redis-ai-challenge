    def execute_multi_hop_reasoning(self, concept_chain: List[str]) -> Dict[str, Any]:
        """Execute complex reasoning across multiple concept relationships"""
        
        print(f"🔗 MULTI-HOP REASONING: {' → '.join(concept_chain)}")
        
        # Start with files from first concept
        current_files = set(json.loads(self.r.hget(f'concept:{concept_chain[0]}', 'files') or '[]'))
        
        reasoning_chain = []
        
        # Apply each concept filter in sequence
        for i, concept in enumerate(concept_chain[1:], 1):
            concept_files = set(json.loads(self.r.hget(f'concept:{concept}', 'files') or '[]'))
            
            # Files that bridge current set with this concept
            bridge_files = current_files & concept_files
            
            reasoning_chain.append({
                'step': i,
                'concept': concept,
                'files_before': len(current_files),
                'files_after': len(bridge_files),
                'bridge_strength': len(bridge_files) / min(len(current_files), len(concept_files))
            })
            
            current_files = bridge_files
            
            print(f"  Step {i}: {concept} → {len(bridge_files)} files (strength: {reasoning_chain[-1]['bridge_strength']:.2f})")
        
        return {
            'final_files': list(current_files)[:5],
            'reasoning_chain': reasoning_chain,
            'total_steps': len(concept_chain),
            'synthesis_strength': reasoning_chain[-1]['bridge_strength'] if reasoning_chain else 0
        }
    
    def generate_semantic_refactoring_plan(self) -> Dict[str, Any]:
        """Generate refactoring recommendations using semantic analysis"""
        
        print("🔄 GENERATING SEMANTIC REFACTORING PLAN...")
        
        # Find architectural centers (files bridging most concepts)
        concepts = ['redis_patterns', 'ai_agents', 'emacs_integration', 'homoiconic', 'self_modification']
        
        file_concept_count = {}
        for concept in concepts:
            concept_files = json.loads(self.r.hget(f'concept:{concept}', 'files') or '[]')
            for file_name in concept_files:
                file_concept_count[file_name] = file_concept_count.get(file_name, 0) + 1
        
        # Files that bridge 4+ concepts are architectural centers
        architectural_centers = {f: count for f, count in file_concept_count.items() if count >= 4}
        
        # Find overcoupled files (too many concepts) and undercoupled files
        overcoupled = {f: count for f, count in architectural_centers.items() if count >= 5}
        optimal_centers = {f: count for f, count in architectural_centers.items() if count == 4}
        
        refactoring_plan = {
            'architectural_centers': list(optimal_centers.keys())[:3],
            'overcoupled_files': list(overcoupled.keys())[:3], 
            'recommendations': []
        }
        
        # Generate specific recommendations
        if overcoupled:
            refactoring_plan['recommendations'].append({
                'action': 'split_overcoupled',
                'target': list(overcoupled.keys())[0],
                'reason': f'Bridges {overcoupled[list(overcoupled.keys())[0]]} concepts - too many responsibilities'
            })
            
        if optimal_centers:
            refactoring_plan['recommendations'].append({
                'action': 'promote_to_coordinator', 
                'target': list(optimal_centers.keys())[0],
                'reason': f'Optimal 4-concept bridge - perfect for coordination'
            })
        
        for rec in refactoring_plan['recommendations']:
            print(f"  📋 {rec['action']}: {rec['target']}")
            print(f"     Reason: {rec['reason']}")
        
        return refactoring_plan
    
